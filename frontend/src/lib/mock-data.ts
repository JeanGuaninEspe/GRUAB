export function getDashboardMetrics(): DashboardMetrics {
  const totalAmb = MOCK_AMBULANCIAS.length;
  const totalGru = MOCK_GRUAS.length;
  const totalPat = MOCK_PATRULLAJES.length;
  const kmPat = MOCK_PATRULLAJES.reduce((acc, p) => acc + p.km_recorridos, 0);

  const ambMtop = MOCK_AMBULANCIAS.filter((a) => a.reportado_mtop).length;
  const gruMtop = MOCK_GRUAS.filter((g) => g.reportado_mtop).length;
  const mtopPercent = Math.round(((ambMtop + gruMtop) / (totalAmb + totalGru)) * 100);

  const criticosAmb = MOCK_AMBULANCIAS.filter(
    (a) => a.severidad === "GRAVE" || a.severidad === "FATAL"
  ).length;
  const criticosGru = MOCK_GRUAS.filter((g) => g.severidad === "GRAVE" || g.severidad === "FATAL")
    .length;

  return {
    totalAmbulancias: totalAmb,
    totalGruas: totalGru,
    totalPatrullajes: totalPat,
    kmPatrullados: kmPat,
    mtopSincronizadosPercent: mtopPercent,
    casosCriticos: criticosAmb + criticosGru,
    tiempoPromedioRespuestaMin: 12.4,
  };
}

